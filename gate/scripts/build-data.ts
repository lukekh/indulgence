// Builds the bundled safety data:
//   src/safety/data/latin-words.ts — ~20k Latin word forms (folded), by frequency in the
//                                     public-domain Clementine Vulgate, plus the canned prayers.
//   src/safety/data/denylist.ts     — multilingual denylist from LDNOOBW (CC BY 4.0), minus
//                                     entries that are ordinary Latin words (e.g. "cum").
//
// Usage: npm run build:data -- --vulgate <dir of eBible latVUC *_read.txt> --ldnoobw <dir of language files>
// Sources:
//   https://ebible.org/Scriptures/latVUC_readaloud.zip (Public Domain)
//   https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words (CC BY 4.0)

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { foldLatin, words, denylistTokens, foldForDenylist } from '../src/safety/normalize.js';
import canned from '../../shared/canned-prayers.json';

const LATIN_FORMS = 20_000;
// Scripts written without spaces between words: match these entries as substrings.
const NO_SPACE_SCRIPT = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Thai}]/u;

function arg(name: string): string {
  const i = process.argv.indexOf(`--${name}`);
  const v = i >= 0 ? process.argv[i + 1] : undefined;
  if (!v) throw new Error(`missing --${name}`);
  return v;
}

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '../src/safety/data');
mkdirSync(outDir, { recursive: true });

// --- Latin -------------------------------------------------------------------
const counts = new Map<string, number>();
const vulgateDir = arg('vulgate');
for (const f of readdirSync(vulgateDir)) {
  if (!f.endsWith('_read.txt') || f.includes('_000_')) continue;
  for (const w of words(readFileSync(join(vulgateDir, f), 'utf8'))) {
    const k = foldLatin(w);
    counts.set(k, (counts.get(k) ?? 0) + 1);
  }
}
const ranked = [...counts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
const latin = new Set(ranked.slice(0, LATIN_FORMS).map(([w]) => w));
for (const p of canned.prayers) for (const w of words(p.text)) latin.add(foldLatin(w));
// A few liturgical forms common in generated prayers but rare in the Vulgate.
for (const w of ['eleison', 'kyrie', 'christe', 'oremus', 'amen', 'alleluia', 'requiescat', 'requiescant', 'intentio', 'ora', 'orate']) {
  latin.add(foldLatin(w));
}
const latinSorted = [...latin].filter((w) => w.length > 0).sort();
console.log(`latin: ${counts.size} distinct forms in source, kept ${latinSorted.length}`);
writeFileSync(
  join(outDir, 'latin-words.ts'),
  `// @generated by scripts/build-data.ts — Latin word forms from the Clementine Vulgate (Public Domain).\n` +
    `export const LATIN_WORDS = ${JSON.stringify(latinSorted.join('\n'))};\n`,
);

// --- Denylist ----------------------------------------------------------------
const ldnoobwDir = arg('ldnoobw');
const tokenEntries = new Set<string>();
const substringEntries = new Set<string>();
const collisions: string[] = [];
for (const f of readdirSync(ldnoobwDir).sort()) {
  if (!f.endsWith('.txt')) continue;
  for (const line of readFileSync(join(ldnoobwDir, f), 'utf8').split('\n')) {
    const entry = line.trim();
    if (!entry) continue;
    if (NO_SPACE_SCRIPT.test(entry)) {
      substringEntries.add(foldForDenylist(entry).replace(/\s+/g, ''));
      continue;
    }
    const toks = denylistTokens(entry);
    if (toks.length === 0) continue;
    if (toks.length === 1 && toks[0]!.length < 3) continue;
    if (toks.length === 1 && latin.has(foldLatin(toks[0]!))) {
      collisions.push(`${f.replace('.txt', '')}:${toks[0]}`);
      continue;
    }
    tokenEntries.add(toks.join(' '));
  }
}
console.log(`denylist: ${tokenEntries.size} token entries, ${substringEntries.size} substring entries`);
console.log(`dropped as ordinary Latin words: ${collisions.join(', ')}`);
writeFileSync(
  join(outDir, 'denylist.ts'),
  `// @generated by scripts/build-data.ts — derived from LDNOOBW (CC BY 4.0):\n` +
    `// https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words\n` +
    `// Entries are folded (lower case, no diacritics, leetspeak undone). Do not edit.\n` +
    `export const DENY_TOKENS = ${JSON.stringify([...tokenEntries].sort().join('\n'))};\n` +
    `export const DENY_SUBSTRINGS = ${JSON.stringify([...substringEntries].sort().join('\n'))};\n` +
    `export const DENY_LATIN_EXCEPTIONS = ${JSON.stringify(collisions.join('\n'))};\n`,
);
