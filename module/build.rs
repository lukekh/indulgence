//! Generates `constants.rs` from `../shared/constants.json`, the single source of
//! truth shared with the gate and the web client.

use std::{env, fmt::Write as _, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let src = manifest.join("../shared/constants.json");
    println!("cargo:rerun-if-changed={}", src.display());
    let json: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&src).expect("read shared/constants.json"))
            .expect("parse shared/constants.json");

    let mut out = String::from("// @generated by build.rs from shared/constants.json — do not edit.\n");
    for (key, value) in json.as_object().expect("object") {
        if key.starts_with('$') {
            continue;
        }
        match value {
            serde_json::Value::Number(n) if n.is_i64() => {
                writeln!(out, "pub const {key}: i64 = {};", n.as_i64().unwrap()).unwrap();
            }
            serde_json::Value::Number(n) => {
                writeln!(out, "pub const {key}: f64 = {:?};", n.as_f64().unwrap()).unwrap();
            }
            serde_json::Value::Array(items) if items.iter().all(|v| v.is_i64()) => {
                let list: Vec<String> = items.iter().map(|v| v.as_i64().unwrap().to_string()).collect();
                writeln!(out, "pub const {key}: [i64; {}] = [{}];", list.len(), list.join(", ")).unwrap();
            }
            serde_json::Value::Array(items) if key == "SPEND_TIERS" => {
                writeln!(out, "pub const {key}: [SpendTier; {}] = [", items.len()).unwrap();
                for t in items {
                    writeln!(
                        out,
                        "    SpendTier {{ min: {}, vestment: {:?}, candle: {:?}, burn_h: {} }},",
                        t["min"].as_u64().unwrap(),
                        t["vestment"].as_str().unwrap(),
                        t["candle"].as_str().unwrap(),
                        t["burn_h"].as_u64().unwrap()
                    )
                    .unwrap();
                }
                writeln!(out, "];").unwrap();
            }
            other => panic!("unsupported constant {key}: {other}"),
        }
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("constants.rs");
    fs::write(dest, out).unwrap();
}
